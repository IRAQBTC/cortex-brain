#!/usr/bin/env node
'use strict';

const fs = require('fs');
const path = require('path');
const Database = require('better-sqlite3');

const CONFIG = {
  dbPath: process.env.CORTEX_DB_PATH || path.join(process.cwd(), 'cortex-brain.db'),
};

const COLORS = {
  reset: '\x1b[0m',
  green: '\x1b[32m',
  cyan: '\x1b[36m',
  yellow: '\x1b[33m',
  red: '\x1b[31m'
};

function generateContext() {
  try {
    if (!fs.existsSync(CONFIG.dbPath)) throw new Error('Database not found. Run scanner.js first.');
    
    const db = new Database(CONFIG.dbPath, { readonly: true, fileMustExist: true });
    
    const files = db.prepare("SELECT name, file_path, content FROM nodes WHERE kind='file'").all();
    const functions = db.prepare("SELECT name, file_path, content, signature, jsdoc FROM nodes WHERE kind='function'").all();
    const classes = db.prepare("SELECT name, file_path, content FROM nodes WHERE kind='class'").all();
    const methods = db.prepare("SELECT name, file_path, content, signature FROM nodes WHERE kind='method'").all();

    let md = `# 🧠 Cortex Project Context\n\n`;
    md += `> Auto-generated by Cortex. Provide this file to your AI assistant to prevent hallucinations.\n\n`;

    md += `## 📂 Project Files (${files.length})\n`;
    files.forEach(f => { md += `- \`${f.name}\` (Path: \`${f.file_path}\`)\n`; });

    md += `\n## 🏗️ Classes (${classes.length})\n`;
    classes.forEach(c => {
      md += `### \`${c.name}\`\n`;
      md += `**Location:** \`${c.file_path}\`\n\n`;
      md += `\`\`\`javascript\n${c.content}\n\`\`\`\n\n`;
    });

    md += `\n## ⚙️ Core Functions (${functions.length})\n`;
    functions.forEach(f => { 
      md += `### \`${f.name}()\`\n`;
      if (f.jsdoc) md += `**JSDoc:**\n\`\`\`\n${f.jsdoc}\n\`\`\`\n\n`;
      md += `**Signature:** \`${f.signature}\`\n`;
      md += `**Location:** \`${f.file_path}\`\n\n`;
      md += `\`\`\`javascript\n${f.content}\n\`\`\`\n\n`;
    });

    if (methods.length > 0) {
      md += `\n## 🔧 Methods (${methods.length})\n`;
      methods.forEach(m => {
        md += `### \`${m.name}()\`\n`;
        md += `**Signature:** \`${m.signature}\`\n`;
        md += `**Location:** \`${m.file_path}\`\n\n`;
        md += `\`\`\`python\n${m.content}\n\`\`\`\n\n`;
      });
    }

    md += `\n---\n*Generated by Cortex CLI - The Deterministic Brain.*\n`;

    fs.writeFileSync('CORTEX_CONTEXT.md', md);
    
    console.log(`\n${COLORS.green}✅ Context Generated Successfully!${COLORS.reset}`);
    console.log(`   File: ${COLORS.cyan}CORTEX_CONTEXT.md${COLORS.reset}`);
    console.log(`   Size: ${(md.length / 1024).toFixed(2)} KB`);
    console.log(`\n💡 ${COLORS.yellow}What to do next:${COLORS.reset}`);
    console.log(`   Copy the contents of CORTEX_CONTEXT.md and paste it into ChatGPT or Claude.`);
    console.log(`   The AI will now know exactly what your project contains, including full code.\n`);
    
    db.close();
  } catch (error) {
    console.error(`${COLORS.red}❌ Error:${COLORS.reset} ${error.message}`);
  }
}

generateContext();